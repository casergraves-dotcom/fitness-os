export function getExerciseDisplayName(
  exerciseDefinitionId: string | undefined,
  fallbackName: string
) {
  if (!exerciseDefinitionId) {
    return fallbackName;
  }

  return (
    exerciseLibrary.find(
      (exercise) =>
        exercise.id === exerciseDefinitionId
    )?.name ?? fallbackName
  );
}
